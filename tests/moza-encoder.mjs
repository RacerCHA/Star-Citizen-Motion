import assert from 'node:assert/strict';
import {MozaEncoder,DCS_KEYS,G} from '../moza-packet.mjs';
let seq=0;
const base={source:'star-citizen-dbox',schema_version:1,session_id:'test',stream_id:'1',mapping_valid:true};
const event=(key,meanings=[],values=[])=>({...base,seq:++seq,event_key:key,meanings,values});
const frame=()=>({...event(3,[4,92,38],[1,.5,[0,2*G,0]]),acceleration_m_s2:{x:-2*G,y:3*G,z:6000},angular_velocity_rad_s:{x:1,y:2,z:3},velocity_m_s:{x:0,y:650,z:0}});
const m=new MozaEncoder();
m.ingest(event(1,[30],['TEST']),0);m.ingest(event(10,[38],[1]),1);m.ingest(frame(),2);
let s=m.snapshot(2);assert.equal(s.active,true);assert.equal(s.values.tas,231.5);assert.equal(s.values.ias,231.5);
assert.equal(s.values.acc_x,3);assert.equal(s.values.acc_z,-2);assert.equal(s.values.acc_y,6000/G);
assert.deepEqual([s.values.euler_vx,s.values.euler_vy,s.values.euler_vz],[2,3,1]);assert.equal(s.values.gear_value,.5);
assert.deepEqual(s.frame.split(';').filter(Boolean).map(t=>t.split(',')[0]),DCS_KEYS);
assert.ok(!/NaN|Infinity|undefined/.test(s.frame));
const shells=s.values.cannon_shells;
const gun=event(5,[104,171],[1,1]);m.ingest(gun,3);assert.equal(m.snapshot(3).values.cannon_shells,shells-1);
m.ingest(gun,4);assert.equal(m.snapshot(4).values.cannon_shells,shells-1,'duplicate source packet must not fire again');
m.ingest(event(6,[104,171],[1,1]),5);assert.equal(m.snapshot(5).values.weapon,'SC-Ordnance-4.4.7.31*9999');
m.ingest(event(4,[41,43],[1,.5]),6);assert.equal(m.snapshot(6).values.afterburner_1,1);
m.ingest(event(7,[104],[1]),7);assert.equal(m.snapshot(7).values.engine_rpm_left,100);
m.ingest(event(10,[38],[0]),8);assert.equal(m.snapshot(8).active,false);
m.ingest(event(5,[104,171],[1,1]),9);assert.equal(m.weaponEvents,1,'on-foot weapons excluded');
m.ingest(event(10,[38],[1]),10);m.ingest(frame(),11);assert.equal(m.snapshot(400).active,false);
m.ingest(event(10,[38],[1]),401);const rapid=frame();rapid.velocity_m_s.y=1300;m.ingest(rapid,402);assert.equal(m.snapshot(402).values.tas,463,'no hidden speed clipping');
m.ingest(event(2),403);assert.equal(m.snapshot(403).active,false);
m.ingest({...event(3),...frame(),mapping_valid:false},404);assert.equal(m.snapshot(404).active,false);
m.ingest({...frame(),stream_id:'2'},405);assert.equal(m.snapshot(405).active,false,'new stream must establish pilot role');
m.ingest({...event(10,[38],[1]),stream_id:'2'},406);assert.equal(m.snapshot(406).active,true);
const bad={...frame(),stream_id:'2',acceleration_m_s2:{x:NaN,y:0,z:0}};m.ingest(bad,407);assert.equal(m.snapshot(407).active,false);
assert.throws(()=>new MozaEncoder({aircraft:'name;spoof,1'}));assert.throws(()=>new MozaEncoder({shipSpeedScale:0}));
console.log('PASS: full DCS keys, axes/units, uncapped acceleration and speed, weapon events, boost/gear, pilot/stream/expiry gates.');
